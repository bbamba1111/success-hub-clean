/**
 * Stage Benchmark Registry™ (Phase 1)
 * ---------------------------------------------------------------------------
 * The canonical, data-only registry of what every existing Entrepreneur
 * Success Assessment™ Operating Practice™ should look like at each of the
 * four Business Stages™ — Launch™, Growth™, Scale™, Legacy™ — across all six
 * Business Capability Maturity™ dimensions (Know/Show/Build/Own/Prove/
 * Measure).
 *
 * This file intentionally reuses the EXISTING 20 Operating Practices™ across
 * the EXISTING 8 Operating Pillars™ (`lib/entrepreneur-success/esa-registry`).
 * No new pillars, practices, or ESA sections are invented here. No scoring or
 * recommendation logic lives in this file — see `registry-helpers.ts` for the
 * read-only query surface later phases (ESA, Founder GPS™) will consume.
 */

import type { BusinessStage } from "@/lib/business-stage/business-stage"
import type { OperatingPillarId } from "@/lib/entrepreneur-success/types"
import type { StageBenchmark } from "./types"

type StageRow = Omit<StageBenchmark, "id" | "businessArea" | "practiceId" | "capability">

function stage(businessStage: BusinessStage, fields: Omit<StageRow, "businessStage">): StageRow {
  return { businessStage, ...fields }
}

function practice(
  practiceId: string,
  businessArea: OperatingPillarId,
  capability: string,
  rows: StageRow[],
): StageBenchmark[] {
  return rows.map((row) => ({
    id: `${practiceId}--${row.businessStage}`,
    businessArea,
    practiceId,
    capability,
    ...row,
  }))
}

